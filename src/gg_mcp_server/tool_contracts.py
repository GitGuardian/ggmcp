"""Dump the contract of every registered tool to ``tool-contracts.json``.

The file lists, for each tool, what an MCP client sees in ``tools/list`` (name,
title, description, input and output JSON Schemas, annotations) plus the token
scopes that gate it. It is committed at the repository root, attached to each
GitHub release, and checked against the code by ``tests/test_tool_contracts.py``.

Regenerate it after changing a tool::

    make tool-contracts

Building the contracts needs no GitGuardian token and no network: the server is
composed in memory and its tools are listed without running the middleware that
filters them by the caller's scopes.
"""

import asyncio
import json
import sys
from pathlib import Path
from typing import Any

from gg_api_core.mcp_server import AbstractGitGuardianFastMCP, GitGuardianAuthorizationHeaderMCP
from gg_api_core.oauth_proxy_auth import PassThroughTokenVerifier
from gg_mcp_server.register_tools import register_tools

TOOL_CONTRACTS_FILENAME = "tool-contracts.json"
REGENERATE_COMMAND = "make tool-contracts"


def _build_tools_server() -> AbstractGitGuardianFastMCP:
    """Compose a server with every production tool, independently of the environment.

    The authentication mode does not change which tools are registered or their
    schemas, so the header mode is used: it reads no settings and fetches nothing.
    """
    mcp = GitGuardianAuthorizationHeaderMCP("GitGuardian", auth=PassThroughTokenVerifier())
    register_tools(mcp)
    return mcp


async def build_tool_contracts() -> dict[str, Any]:
    """Return the contracts of every registered tool, sorted by tool name."""
    mcp = _build_tools_server()
    tools = await mcp.list_tools(run_middleware=False)
    contracts = []
    for tool in sorted(tools, key=lambda t: t.name):
        wire = tool.to_mcp_tool().model_dump(mode="json", by_alias=True, exclude_none=True)
        # FastMCP's own metadata (tags) is not part of the tool's contract.
        wire.pop("_meta", None)
        wire["requiredScopes"] = sorted(mcp._tool_scopes.get(tool.name, set()))
        contracts.append(wire)
    return {
        "$comment": f"Generated by `{REGENERATE_COMMAND}`; do not edit by hand.",
        "tools": contracts,
    }


def render_tool_contracts(contracts: dict[str, Any]) -> str:
    """Serialize contracts deterministically: sorted keys, two-space indent, trailing newline."""
    return json.dumps(contracts, indent=2, sort_keys=True, ensure_ascii=False) + "\n"


def main(argv: list[str] | None = None) -> int:
    """Write the contracts to the path given as first argument, or ``tool-contracts.json``."""
    args = sys.argv[1:] if argv is None else argv
    path = Path(args[0]) if args else Path(TOOL_CONTRACTS_FILENAME)
    contracts = asyncio.run(build_tool_contracts())
    path.write_text(render_tool_contracts(contracts), encoding="utf-8")
    print(f"Wrote {len(contracts['tools'])} tool contracts to {path}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
